class TermDictionary:
    def __init__(self, terms: dict[str, str] = COMMON_TERMS):
        # Sort by key length descending so longer phrases match first
        self._terms = sorted(terms.items(), key=lambda x: -len(x[0]))

    def apply(self, text: str) -> str:
        for bn, en in self._terms:
            text = text.replace(bn, en)
        return text
